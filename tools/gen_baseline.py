#!/usr/bin/env python3
"""Generate the bootstrap disassembly baseline for LSDj.

A fresh disassembly starts as a single ``INCBIN`` of the base ROM, split into
one RGBDS section per 16 KiB bank. This trivially reassembles to a byte-perfect
copy of the original ROM, which gives us a green ``make compare`` from day one.

The reverse-engineering work then proceeds by *carving*: replacing slices of
these ``INCBIN`` ranges with real disassembled code and data, one routine at a
time, while ``make compare`` keeps the build honest (byte-for-byte identical).

This generator is a *one-time bootstrap*. Once you start editing ``src/main.asm``
by hand, do not re-run it (it would clobber your work). It is kept in the tree
for reproducibility and documentation of how the baseline was produced.

Usage:
    tools/gen_baseline.py [ROM] [-o OUTPUT]

Defaults:
    ROM     lsdj9_4_0.gb
    OUTPUT  src/main.asm
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

BANK_SIZE = 0x4000  # 16 KiB


def generate(rom_path: Path, rom_incbin_name: str) -> str:
    size = rom_path.stat().st_size
    if size % BANK_SIZE != 0:
        sys.exit(
            f"error: ROM size {size} (0x{size:X}) is not a multiple of "
            f"the {BANK_SIZE} (0x{BANK_SIZE:X}) byte bank size"
        )
    num_banks = size // BANK_SIZE

    lines: list[str] = [
        "; LSDj disassembly bootstrap baseline -- GENERATED by tools/gen_baseline.py",
        ";",
        "; Every bank is currently an opaque INCBIN of the base ROM, so the build is",
        "; byte-for-byte identical to the original. Reverse engineering proceeds by",
        "; replacing these INCBIN ranges with real disassembled code/data while",
        "; `make compare` stays green. See AGENTS.md for the carving workflow.",
        "",
        'INCLUDE "include/hardware.inc"',
        "",
    ]

    for bank in range(num_banks):
        offset = bank * BANK_SIZE
        if bank == 0:
            lines.append(f'SECTION "ROM Bank $000", ROM0[$0000]')
        else:
            lines.append(
                f'SECTION "ROM Bank ${bank:03X}", ROMX[$4000], BANK[${bank:03X}]'
            )
        lines.append(f'INCBIN "{rom_incbin_name}", ${offset:06X}, ${BANK_SIZE:04X}')
        lines.append("")

    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "rom",
        nargs="?",
        default="lsdj9_4_0.gb",
        help="path to the base ROM (default: lsdj9_4_0.gb)",
    )
    parser.add_argument(
        "-o",
        "--output",
        default="src/main.asm",
        help="output assembly file (default: src/main.asm)",
    )
    args = parser.parse_args()

    rom_path = Path(args.rom)
    if not rom_path.is_file():
        sys.exit(f"error: ROM not found: {rom_path}")

    # INCBIN path is resolved relative to the repo root (where rgbasm runs).
    rom_incbin_name = rom_path.name
    asm = generate(rom_path, rom_incbin_name)

    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(asm)
    num_banks = rom_path.stat().st_size // BANK_SIZE
    print(f"wrote {out_path} ({num_banks} banks from {rom_path})")


if __name__ == "__main__":
    main()
