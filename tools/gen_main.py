#!/usr/bin/env python3
"""Generate src/main.asm from the set of carved banks.

For each of the ROM's 64 banks: if a carved `src/bankNN.asm` exists, INCLUDE it;
otherwise emit a SECTION that INCBINs that bank from the base ROM. This makes
carving a new bank a two-step, systematic operation:

    tools/disasm.py --rom lsdj9_4_0.gb --bank N --symbols src/bankNN.sym ... \
        -o src/bankNN.asm
    tools/gen_main.py        # rewire main.asm
    make compare             # must stay green

Run with no args after adding/removing a src/bankNN.asm.
"""

from __future__ import annotations

from pathlib import Path

BANK_SIZE = 0x4000
ROM_NAME = "lsdj9_4_0.gb"
SRC = Path(__file__).resolve().parents[1] / "src"
NUM_BANKS = 64


def main() -> None:
    lines = [
        "; GENERATED by tools/gen_main.py -- do not edit by hand.",
        ";",
        "; Carved banks are INCLUDEd from src/bankNN.asm; the rest are INCBIN'd",
        "; from the base ROM. To carve a bank: create src/bankNN.asm (see",
        "; tools/disasm.py), then re-run tools/gen_main.py.",
        "",
        'INCLUDE "include/hardware.inc"',
        "",
    ]
    carved = []
    for bank in range(NUM_BANKS):
        asm = SRC / f"bank{bank:02x}.asm"
        offset = bank * BANK_SIZE
        if asm.is_file():
            carved.append(bank)
            lines.append(f'INCLUDE "src/bank{bank:02x}.asm"')
        elif bank == 0:
            lines.append('SECTION "ROM Bank $000", ROM0[$0000]')
            lines.append(f'INCBIN "{ROM_NAME}", ${offset:06X}, ${BANK_SIZE:04X}')
        else:
            lines.append(
                f'SECTION "ROM Bank ${bank:03X}", ROMX[$4000], BANK[${bank:03X}]')
            lines.append(f'INCBIN "{ROM_NAME}", ${offset:06X}, ${BANK_SIZE:04X}')
        lines.append("")

    (SRC / "main.asm").write_text("\n".join(lines) + "\n")
    print(f"wrote src/main.asm; carved banks: "
          + (", ".join(f"${b:02X}" for b in carved) or "(none)"))


if __name__ == "__main__":
    main()
