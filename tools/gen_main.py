#!/usr/bin/env python3
"""Generate src/main.asm from the set of carved banks.

For each of the ROM's 64 banks: if a carved `src/bankNN.asm` exists, INCLUDE it;
an empty kit slot (all $FF) is a `ds`; otherwise emit a SECTION that INCBINs
that bank from the base ROM. This makes
carving a new bank a two-step, systematic operation:

    tools/disasm.py --rom lsdj9_4_0.gb --bank N --symbols src/bankNN.sym ... \
        -o src/bankNN.asm
    tools/gen_main.py        # rewire main.asm
    make compare             # must stay green

Run with no args after adding/removing a src/bankNN.asm.
"""

from __future__ import annotations

import re
from pathlib import Path

BANK_SIZE = 0x4000
# The base ROM: override with LSDJ_BASEROM=/path/to/rom.gb (the Makefile passes
# BASEROM through). The generated main.asm INCBINs this exact path, so a ROM
# outside the repo root works too (main.asm is generated, never committed).
import os as _os
ROM_NAME = _os.environ.get("LSDJ_BASEROM", "lsdj9_4_0.gb")
ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
NUM_BANKS = 64

# LSDj sample-kit bank layout (each kit is a full 16 KiB ROMX bank at $4000):
#   $4000 +$22  sample offset table: 16 x 2-byte start pointers (+ $6040 marker)
#   $4022 +$30  16 x 3-char sample names
#   $4052 +$0E  6-char kit name (+ padding)
#   $4060 +$3FA0 4-bit PCM sample data
# Labelling these (instead of one opaque INCBIN) gives the debugger a symbol for
# every referenced kit address -- the sample player's reads then show as offsets
# from KitNAME_Samples instead of _DATA_. Byte-identical (contiguous INCBINs).
# Header parts (before the sample data at $4060). The sample data is split per
# named sample from the pointer table -- see kit_sample_chunks.
KIT_HEADER = [
    (0x00, 0x22, "Ptrs", "sample offset table (16 x 2-byte ptrs) + $6040 marker"),
    (0x22, 0x30, "Names", "16 x 3-char sample names"),
    (0x52, 0x06, "KitName", "6-char kit name"),
    (0x58, 0x08, "KitMeta", "kit header tail: pad + flags/loop bytes"),
]


def _token(raw: bytes, fallback: str) -> str:
    """ASCII bytes -> a label-safe token (alnum only), or `fallback` if empty."""
    return re.sub(r"[^0-9A-Za-z]", "", raw.decode("ascii", "replace")) or fallback


def kit_of(rom: bytes, bank: int) -> tuple[str, str] | None:
    """If `bank` is a sample kit (has the $6040 marker), return (label_token,
    display_name); else None. The token is a label-safe form of the kit name."""
    base = bank * BANK_SIZE
    if rom[base] != 0x60 or rom[base + 1] != 0x40:
        return None
    name = bytes(rom[base + 0x52:base + 0x58]).decode("ascii", "replace").strip()
    return _token(bytes(rom[base + 0x52:base + 0x58]), f"{bank:02X}"), name


def kit_sample_chunks(rom: bytes, bank: int, token: str) -> list[tuple[int, int, str]]:
    """Split the sample-data region ($4060-$8000) at each *named* sample start
    from the pointer table, returning (rel_offset, size, label). Sample names come
    from the ROM ($4022), so a kit renamed by an external tool labels correctly;
    duplicates within a kit get a numeric suffix. The last sample runs to $8000
    (trailing pad folds in). Byte-identical: the chunks are contiguous."""
    base = bank * BANK_SIZE
    starts: list[tuple[int, str]] = []
    for i in range(16):
        p = rom[base + 2 * i] | (rom[base + 2 * i + 1] << 8)
        nm = _token(bytes(rom[base + 0x22 + 3 * i:base + 0x22 + 3 * i + 3]), "")
        if 0x4060 <= p < 0x8000 and nm:
            starts.append((p, nm))
    starts.sort()
    chunks: list[tuple[int, int, str]] = []
    used: dict[str, int] = {}
    for j, (s, nm) in enumerate(starts):
        e = starts[j + 1][0] if j + 1 < len(starts) else 0x8000
        used[nm] = used.get(nm, -1) + 1
        label = f"Kit{token}_{nm}" + (f"_{used[nm]}" if used[nm] else "")
        chunks.append((s - 0x4000, e - s, label))
    if not chunks:                                   # no named samples: one blob
        return [(0x60, 0x3FA0, f"Kit{token}_Samples")]
    if chunks[0][0] != 0x60:                         # data before the first sample
        chunks.insert(0, (0x60, chunks[0][0] - 0x60, f"Kit{token}_Samples"))
    return chunks


def kit_section(rom: bytes, bank: int, token: str, name: str) -> list[str]:
    off = bank * BANK_SIZE
    out = [f'SECTION "ROM Bank ${bank:03X} (kit {name})", ROMX[$4000], BANK[${bank:03X}]']
    for rel, size, part, comment in KIT_HEADER:
        out.append(f"Kit{token}_{part}:: ; {comment}")
        out.append(f'INCBIN "{ROM_NAME}", ${off + rel:06X}, ${size:04X}')
    for rel, size, label in kit_sample_chunks(rom, bank, token):
        out.append(f"{label}::")
        out.append(f'INCBIN "{ROM_NAME}", ${off + rel:06X}, ${size:04X}')
    return out


def main() -> None:
    lines = [
        "; GENERATED by tools/gen_main.py -- do not edit by hand.",
        ";",
        "; Carved banks are INCLUDEd from src/bankNN.asm, the empty kit slots are",
        "; $FF, and the kits are INCBIN'd from the base ROM. To carve a bank:",
        "; create src/bankNN.asm (see tools/disasm.py), then re-run tools/gen_main.py.",
        "",
        'INCLUDE "include/hardware.inc"',
        'INCLUDE "constants/ram.inc"',
        '; named WRAM/HRAM/SRAM sections for the linker map (no labels/bytes)',
        'INCLUDE "src/ramsections.asm"',
        "",
    ]
    rom_path = Path(ROM_NAME) if Path(ROM_NAME).is_absolute() else ROOT / ROM_NAME
    rom = rom_path.read_bytes() if rom_path.is_file() else b""

    # Resolve kit labels from ROM content (works on kits a user patched with an
    # external tool). Disambiguate collisions: if a patched ROM names two kits the
    # same, append the bank so labels stay unique (else rgbasm sees dup symbols).
    kit_tokens: dict[int, tuple[str, str]] = {}
    for bank in range(NUM_BANKS):
        if rom and bank != 0 and not (SRC / f"bank{bank:02x}.asm").is_file():
            k = kit_of(rom, bank)
            if k:
                kit_tokens[bank] = k
    dup = {t for t in (tok for tok, _ in kit_tokens.values())
           if sum(tk == t for tk, _ in kit_tokens.values()) > 1}
    for b, (t, n) in list(kit_tokens.items()):
        if t in dup:
            kit_tokens[b] = (f"{t}_{b:02X}", n)

    carved, kits, empty = [], [], []
    for bank in range(NUM_BANKS):
        asm = SRC / f"bank{bank:02x}.asm"
        offset = bank * BANK_SIZE
        if asm.is_file():
            carved.append(bank)
            lines.append(f'INCLUDE "src/bank{bank:02x}.asm"')
        elif bank in kit_tokens:
            kits.append(bank)
            lines.extend(kit_section(rom, bank, *kit_tokens[bank]))
        elif bank == 0:
            lines.append('SECTION "ROM Bank $000", ROM0[$0000]')
            lines.append(f'INCBIN "{ROM_NAME}", ${offset:06X}, ${BANK_SIZE:04X}')
        elif rom and rom[offset:offset + BANK_SIZE] == b"\xff" * BANK_SIZE:
            empty.append(bank)
            lines.append(
                f'SECTION "ROM Bank ${bank:03X} (no kit)", ROMX[$4000], BANK[${bank:03X}]')
            lines.append("; A kit slot with no kit in it: KitExists finds no $4060 marker.")
            lines.append(f"\tds ${BANK_SIZE:04X}, $ff")
        else:
            lines.append(
                f'SECTION "ROM Bank ${bank:03X}", ROMX[$4000], BANK[${bank:03X}]')
            lines.append(f'INCBIN "{ROM_NAME}", ${offset:06X}, ${BANK_SIZE:04X}')
        lines.append("")

    (SRC / "main.asm").write_text("\n".join(lines) + "\n")
    print(f"wrote src/main.asm; carved banks: "
          + (", ".join(f"${b:02X}" for b in carved) or "(none)"))
    if kits:
        print(f"labelled {len(kits)} kit banks: "
              + ", ".join(f"${b:02X}" for b in kits))
    if empty:
        print(f"{len(empty)} empty kit slots: ${empty[0]:02X}-${empty[-1]:02X}")


if __name__ == "__main__":
    main()
