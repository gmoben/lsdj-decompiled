#!/usr/bin/env python3
"""Emit the whole annotated disassembly as a single file -- the local
equivalent of copy-pasting Emulicious's debugger view.

The carve already produces per-bank .asm with every symbol applied and bytes
round-tripping exactly; this concatenates them plus a WRAM/HRAM section built
from constants/ram.inc, so you get one greppable listing without opening an
emulator. Regenerate any time with `make listing`.

Usage: tools/gen_listing.py [-o build/listing.asm]
"""
import argparse, glob, os, re


def ram_section():
    """Render the RAM map like the debugger's WRAM/HRAM sections."""
    defs = []
    for ln in open("constants/ram.inc"):
        m = re.match(r"DEF (\w+)\s+EQU \$([0-9A-Fa-f]{4})\s*;?\s*(.*)", ln)
        if m:
            defs.append((int(m.group(2), 16), m.group(1), m.group(3).rstrip()))
    defs.sort()
    out = ["", "; " + "=" * 72, "; RAM / HRAM variables (constants/ram.inc)",
           "; " + "=" * 72]
    prev = None
    for addr, name, cmt in defs:
        region = ("HRAM" if addr >= 0xFF80 else
                  "WRAMX" if addr >= 0xD000 else
                  "WRAM0" if addr >= 0xC000 else "SRAM")
        if prev is None or addr != prev + 1:
            out.append(f'\nSECTION "ram_{addr:04x}", {region}[${addr:04X}]')
        tail = f"  ; {cmt}" if cmt else ""
        out.append(f"{name}:: db{tail}")
        prev = addr
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--output", default="build/listing.asm")
    a = ap.parse_args()
    os.makedirs(os.path.dirname(a.output) or ".", exist_ok=True)
    banks = sorted(glob.glob("src/bank*.asm"))
    parts = [
        "; LSDj 9.4.0 -- full annotated disassembly (generated by "
        "tools/gen_listing.py).",
        "; This is the local stand-in for the Emulicious debugger export: every",
        "; bank carved with all symbols applied, plus the RAM map. Grep it freely.",
        "",
    ]
    for p in banks:
        parts.append(f"; {'=' * 72}\n; {os.path.basename(p)}\n; {'=' * 72}")
        parts.append(open(p).read().rstrip())
    parts.append(ram_section())
    text = "\n".join(parts) + "\n"
    open(a.output, "w").write(text)
    ins = sum(1 for _ in re.finditer(r"; \$[0-9a-f]{4}:", text))
    print(f"==> {a.output}  ({len(text.splitlines())} lines, ~{ins} instructions)")


if __name__ == "__main__":
    main()
