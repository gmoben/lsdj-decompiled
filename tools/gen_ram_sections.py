#!/usr/bin/env python3
"""Generate src/ramsections.asm: named WRAM/HRAM/SRAM SECTIONs for the map file.

Emulicious builds its debugger section tree from the RGBDS .map when one sits
beside the ROM; without RAM sections it falls back to address names
(wram_cbbc, sram_a000, ...). constants/ram.inc is EQU-based (no sections), so
this tool derives label-free sections from it: each contiguous run of defined
bytes becomes `SECTION "<first symbol>", <region>[$addr]` + a single `ds N`.
No labels are emitted (the EQUs stay authoritative; duplicate symbols would
collide) and RAM sections contribute no ROM bytes, so `make compare` is
unaffected. SRAM sections come from gen_sym.SRAM_MAP (the working-song map).

Regenerated by the Makefile whenever ram.inc changes.
"""
import importlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
SRAM_MAP = importlib.import_module("gen_sym").SRAM_MAP  # SRAM single source

DEF_RE = re.compile(r"^DEF\s+(\w+)\s+EQU\s+\$([0-9A-Fa-f]{4})")


def region_of(addr: int):
    if 0xC000 <= addr <= 0xCFFF:
        return "WRAM0", None
    if 0xD000 <= addr <= 0xDFFF:
        return "WRAMX", 1  # default switchable bank
    if 0xFF80 <= addr <= 0xFFFE:
        return "HRAM", None
    return None, None


def contiguous_runs(ram_inc: Path):
    """Yield (start, end, name, region, bank) runs of defined RAM bytes."""
    seen: set[int] = set()
    defs: list[tuple[int, str]] = []
    for line in ram_inc.read_text().splitlines():
        m = DEF_RE.match(line.strip())
        if not m:
            continue
        addr = int(m.group(2), 16)
        if region_of(addr)[0] is None or addr in seen:
            continue  # non-RAM address, or alias (first name wins)
        seen.add(addr)
        defs.append((addr, m.group(1)))
    defs.sort()

    runs: list[tuple[int, int, str, str, int | None]] = []
    for addr, name in defs:
        region, bank = region_of(addr)
        assert region is not None
        if runs and addr == runs[-1][1] + 1 and region == runs[-1][3]:
            start, _, first, reg, bk = runs[-1]
            runs[-1] = (start, addr, first, reg, bk)
        else:
            runs.append((addr, addr, name, region, bank))
    return runs


def ram_sections(ram_inc: Path) -> list[str]:
    out: list[str] = []
    for start, end, name, region, bank in contiguous_runs(ram_inc):
        suffix = f", BANK[{bank}]" if bank is not None else ""
        out.append(f'SECTION "{name}", {region}[${start:04X}]{suffix}')
        out.append(f"\tds {end - start + 1}")
        out.append("")
    return out


def sram_sections() -> list[str]:
    # Keep only top-level structures: the SramProp* field symbols live inside
    # SramProperties and would overlap as sections.
    tops = [(off, name) for off, name in sorted(SRAM_MAP)
            if not (name.startswith("SramProp") and name != "SramProperties")]
    out: list[str] = []
    for i, (off, name) in enumerate(tops):
        end = tops[i + 1][0] if i + 1 < len(tops) else 0x8000
        bank_end = ((off >> 13) + 1) << 13
        end = min(end, bank_end)  # SramInstrNames straddles the bank0/1 seam
        bank, cpu = off >> 13, 0xA000 + (off & 0x1FFF)
        out.append(f'SECTION "{name}", SRAM[${cpu:04X}], BANK[{bank}]')
        out.append(f"\tds {end - off}")
        out.append("")
    return out


def main() -> int:
    lines = [
        "; GENERATED by tools/gen_ram_sections.py from constants/ram.inc --",
        "; do not edit by hand. Named RAM/SRAM sections for the linker map",
        "; (Emulicious names its section tree from the .map). Sections only,",
        "; no labels: the EQUs in ram.inc remain the symbol source.",
        "",
    ]
    lines += ram_sections(ROOT / "constants/ram.inc")
    lines += sram_sections()
    (ROOT / "src/ramsections.asm").write_text("\n".join(lines) + "\n")
    n = sum(1 for l in lines if l.startswith("SECTION"))
    print(f"wrote src/ramsections.asm ({n} sections)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
